#!/usr/bin/env python3
"""Build the testing opponent's deck (make only: the Duel Computer's slot on the deck opponents' page) from a .ydk.

Usage: tools/testdeck.py <deck.ydk> <out.h>     (the Makefile passes TEST_YDK, by default
                                                 /mnt/c/ProjectIgnis/deck/test.ydk, and build/include/test_deck.h)

The header defines MOD_TEST_DECK, TEST_DECK_PORTRAIT (the card number of the first Main Deck card, for the portrait)
and, when TEST_DECK_WANT_CARDS is defined first, sTestDeck[]: the card numbers of the Main Deck, then the Extra Deck
(LoadOpponentDeck puts Fusion Monsters into the Fusion Deck). The Side Deck is not used. Passcodes resolve through the
built password table (build/assets/newcards__passwords.bin, 4 BCD bytes a card ID); a card the game does not have is
left out with a warning. With no .ydk, the header only says so (no MOD_TEST_DECK). When the .ydk resolves to zero cards in this ROM, MOD_TEST_DECK
is still set and sTestDeck is empty (Test Duel starts with no opponent deck).
The header is rewritten only when it changes, so an unchanged deck does not rebuild anything.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
from ydk_io import read_ydk  # noqa: E402

ASSETS = 'build/assets'
# Passcodes the table does not hold: B. Skull Dragon has none in EDS; Dark Paladin was added under 98502115.
ALIASES = {
    11901678: 'B. Skull Dragon',
    98502113: 'Dark Paladin',
    # YGOPRODeck .ydk ids (not the BCD passcodes in new_cards.tsv):
    70095154: 'Cyber Dragon',
    1546123: 'Cyber End Dragon',
    23995346: 'Manticore of Darkness',  # YGOPRODeck .ydk id (in-game passcode 77121851)
    10248389: 'Cyber Blader',
    86099788: 'The Last Warrior from Another Planet',
}
MAIN_MAX = 60
EXTRA_MAX = 20


def bcd(b):
    s = ''.join(f'{x >> 4}{x & 15}' for x in b)
    return int(s) if s.isdigit() else None


def tables():
    pw = open(os.path.join(ASSETS, 'newcards__passwords.bin'), 'rb').read()
    i2n = open(os.path.join(ASSETS, 'newcards__id_to_number.bin'), 'rb').read()
    names = open(os.path.join(ASSETS, 'newcards__names.bin'), 'rb').read()
    by_pass, by_name = {}, {}
    for i in range(1, len(pw) // 4):
        p = bcd(pw[i * 4:i * 4 + 4])
        if p is not None and p not in by_pass:
            by_pass[p] = i
        name = names[i * 0x40:(i + 1) * 0x40].split(b'\0')[0].decode('latin-1')
        by_name.setdefault(name, i)
    for p, name in ALIASES.items():
        if p not in by_pass and name in by_name:
            by_pass[p] = by_name[name]
    number = lambda cid: struct.unpack_from('<H', i2n, cid * 2)[0]
    name = lambda cid: names[cid * 0x40:(cid + 1) * 0x40].split(b'\0')[0].decode('latin-1')
    return by_pass, number, name


def header(path):
    lines = ['/* Generated by tools/testdeck.py from ' + path + '. Do not edit. */']
    if not os.path.exists(path):
        print(f'testdeck: {path} not found: no test opponent', file=sys.stderr)
        return '\n'.join(lines + ['/* no deck file: no test opponent */', ''])
    by_pass, number, name = tables()
    s = read_ydk(path)
    cards = {}
    for sec in ('#main', '#extra'):
        cards[sec] = []
        for p in s[sec]:
            if p in by_pass:
                cards[sec].append(by_pass[p])
            else:
                print(f'testdeck: passcode {p} ({sec[1:]}) is not in the game: left out', file=sys.stderr)
    main, extra = cards['#main'][:MAIN_MAX], cards['#extra'][:EXTRA_MAX]
    deck = main + extra
    if not deck:
        print(f'testdeck: {path}: 0 cards in this ROM — Test Duel with empty opponent deck '
              f'(for make demo, cards must be in new_cards.txt above ------)', file=sys.stderr)
        lines += ['#define MOD_TEST_DECK 1',
                  '/* zero cards: opponent starts with no deck */',
                  '#ifdef TEST_DECK_WANT_CARDS',
                  'static const u16 sTestDeck[] = {',
                  '};',
                  '#endif', '']
        return '\n'.join(lines)
    lines += ['#define MOD_TEST_DECK 1']
    if main:
        lines += [f'#define TEST_DECK_PORTRAIT {number(main[0])}    /* {name(main[0])} */']
    lines += ['#ifdef TEST_DECK_WANT_CARDS',
              f'static const u16 sTestDeck[] = {{    /* Main Deck ({len(main)}), Extra Deck ({len(extra)}) */']
    lines += [f'    {number(cid)},    /* {name(cid)} */' for cid in deck]
    lines += ['};', '#endif', '']
    print(f'testdeck: {path}: {len(main)} Main Deck + {len(extra)} Extra Deck cards', file=sys.stderr)
    return '\n'.join(lines)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    path, out = sys.argv[1], sys.argv[2]
    text = header(path)
    if os.path.exists(out) and open(out, encoding='utf-8').read() == text:
        return
    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    open(out, 'w', encoding='utf-8', newline='\n').write(text)


if __name__ == '__main__':
    main()
