#!/usr/bin/env python3
"""The Yugi-Kaiba format for src/mod_banlist.c: the card pool and the Forbidden/Limited list, as card numbers.

  python3 tools/banlist.py build/include/format_yugi_kaiba.h     # the Makefile runs it

Inputs (repository root): yugi-kaiba.txt, one card name per line (the legal card pool), and yugi-kaiba_ban.json, a
YGOPRODeck-style banlist ("forbidden", "limited", "semiLimited" arrays of entries with a "cardName"). Names are
matched against the built card names (build/assets/newcards__names.bin, original and added cards), first exactly,
then ignoring case, spacing and punctuation, then through ALIASES. A name with no EDS card is reported and skipped:
such a card cannot be in a deck. The header holds two sorted tables of card numbers (alternate-art numbers are the
same card, so only the base number is listed).
"""
import json
import struct
import sys

POOL = 'yugi-kaiba.txt'
BANLIST = 'yugi-kaiba_ban.json'
NAMES = 'build/assets/newcards__names.bin'
ID_TO_NUMBER = 'build/assets/newcards__id_to_number.bin'
NAME_SIZE = 0x40
ALT_ART = 2000
# TCG name -> EDS name, where the two differ beyond case and punctuation.
ALIASES = {
    'Red-Eyes Black Dragon': 'Red-Eyes B. Dragon',
}
LIMITS = {'forbidden': 0, 'limited': 1, 'semiLimited': 2}


def norm(s):
    return ''.join(c for c in s.lower() if c.isalnum())


def main():
    out = sys.argv[1]
    names = open(NAMES, 'rb').read()
    i2n = open(ID_TO_NUMBER, 'rb').read()
    exact, folded = {}, {}
    for cid in range(1, len(i2n) // 2):
        name = names[cid * NAME_SIZE:(cid + 1) * NAME_SIZE].split(b'\0')[0].decode('latin-1')
        number = struct.unpack_from('<H', i2n, cid * 2)[0]
        if number == 0xFFFF or not name:
            continue
        if number >= ALT_ART:
            number -= ALT_ART
        exact.setdefault(name, number)
        folded.setdefault(norm(name), number)

    def lookup(name):
        name = ALIASES.get(name, name)
        return exact.get(name, folded.get(norm(name)))

    missing = []
    pool = set()
    for line in open(POOL, encoding='utf-8'):
        name = line.strip()
        if not name:
            continue
        number = lookup(name)
        if number is None:
            missing.append(name)
        else:
            pool.add(number)
    ban = json.load(open(BANLIST, encoding='utf-8'))
    limits = {}
    for key, limit in LIMITS.items():
        for entry in ban.get(key, []):
            number = lookup(entry['cardName'])
            if number is None:
                missing.append(entry['cardName'])
            else:
                limits[number] = limit
    for name in missing:
        print(f'banlist: no EDS card named "{name}" (skipped)', file=sys.stderr)

    lines = ['/* Generated by tools/banlist.py from yugi-kaiba.txt and yugi-kaiba_ban.json. Do not edit. */',
             f'#define FORMAT_NAME "{ban.get("id", "")}"',
             f'#define FORMAT_POOL_COUNT {len(pool)}',
             f'#define FORMAT_LIMIT_COUNT {len(limits)}',
             '/* The legal card pool, sorted card numbers. */',
             'static const u16 sFormatPool[FORMAT_POOL_COUNT] = {']
    nums = sorted(pool)
    for i in range(0, len(nums), 12):
        lines.append('    ' + ', '.join(str(n) for n in nums[i:i + 12]) + ',')
    lines += ['};', '/* The Forbidden/Limited list: { card number, copies allowed }. */',
              'static const struct FormatLimit sFormatLimits[FORMAT_LIMIT_COUNT] = {']
    lines += [f'    {{ {n}, {l} }},' for n, l in sorted(limits.items())]
    lines += ['};', '']
    data = '\n'.join(lines)
    try:
        if open(out, encoding='utf-8').read() == data:
            return
    except FileNotFoundError:
        pass
    open(out, 'w', encoding='utf-8').write(data)


if __name__ == '__main__':
    main()
