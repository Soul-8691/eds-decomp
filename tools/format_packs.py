#!/usr/bin/env python3
"""Format booster packs: card pools and inverse-usage weights for src/mod_format_packs.c.

  python3 tools/format_packs.py build/include/format_pack_data.h

One pool per selectable format (tools/banlist.py BANLISTS order). Each card in the format pool gets a
uint16 weight inversely proportional to deck usage (same usage/*.json and share math as tools/cardprices.py),
with Limited x3 and Semi-Limited x1.5 on the usage score (higher score -> lower weight). Forbidden cards are
omitted. Cards in the pool with no usage row use a small default share so they are common pulls.

Portrait card numbers (pack icons) follow the format duelists in src/mod_opponents.c.
"""
import bisect
import json
import os
import random
import struct
import sys

sys.path.insert(0, 'tools')
import banlist  # noqa: E402
from cardprices import BASE, EXTRA_DIVISOR, LIMIT_FACTOR, share  # noqa: E402

FORMAT_PACK_ID_FIRST = 601
VANILLA_PACK_INFO_COUNT = 23
WEIGHT_SCALE = 10000
DEFAULT_SHARE_DIVISOR = 50  # pool-only cards: share = 1 / (decks * this)
ROULETTE_SIZE = 65536  # precomputed weighted table; runtime uses RandomBelow(ROULETTE_SIZE)

# enum DuelistId of each format opponent, in BANLISTS order (src/mod_opponents.c).
FORMAT_DUELISTS = [
    4,   # Tristan / Yugi-Kaiba
    6,   # Rex / Critter
    7,   # Espa Roba / Treasure
    9,   # Mako / Imperial
    10,  # Mai / Android
    8,   # Weevil / Joey-Pegasus
    11,  # Rare Hunter / Fiber
    12,  # Arkana / Yata
    14,  # Umbra & Lumis / Scientist
    15,  # Marik / Vampire
    13,  # Strings / Chaos
    16,  # Kaiba / Warrior
    17,  # Ishizu / Goat
    19,  # Yami Bakura / Cyber
    20,  # Yami Yugi / Reaper
]

# Portrait names in BANLISTS order (same cards as the format duelists' icons).
PORTRAIT_NAMES = [
    'La Jinn the Mystical Genie of the Lamp',
    'Sangan',
    'Confiscation',
    'Imperial Order',
    'Jinzo',
    'Graceful Charity',
    'Fiber Jar',
    'Yata-Garasu',
    'Magical Scientist',
    'Vampire Lord',
    'Chaos Emperor Dragon - Envoy of the End',
    'D.D. Warrior Lady',
    'Scapegoat',
    'Cyber Dragon',
    'Spirit Reaper',
]


def usage_maps(stem, lookup, missing):
    """{card number: main+side share}, {card number: extra share}."""
    path = f'usage/{stem}.json'
    try:
        usage = json.load(open(path, encoding='utf-8'))
    except FileNotFoundError:
        return {}, {}, 1
    decks = max(usage.get('decks_processed', 1), 1)
    total, extra = {}, {}
    for entry in usage.get('total', []):
        numbers = lookup(entry['name'])
        if numbers is None:
            missing.append(entry['name'])
            continue
        s = share(entry, decks)
        for number in numbers:
            total[number] = total.get(number, 0.0) + s
    for entry in usage.get('extra', []):
        numbers = lookup(entry['name'])
        if numbers is None:
            missing.append(entry['name'])
            continue
        s = share(entry, decks)
        for number in numbers:
            extra[number] = extra.get(number, 0.0) + s
    return total, extra, decks


def build_roulette(entries, stem):
    """ROULETTE_SIZE card numbers; weighted like the pool (reproducible per format stem)."""
    numbers = [n for n, _ in entries]
    cum = []
    total = 0
    for _, weight in entries:
        total += weight
        cum.append(total)
    rng = random.Random(stem)
    table = []
    for _ in range(ROULETTE_SIZE):
        r = rng.randrange(total)
        idx = bisect.bisect_right(cum, r)
        if idx >= len(numbers):
            idx = len(numbers) - 1
        table.append(numbers[idx])
    return table


def card_weight(number, total, extra, decks, limits):
    if limits.get(number) == 0:
        return None
    s = total.get(number, 0.0) + extra.get(number, 0.0) / EXTRA_DIVISOR
    if s <= 0.0:
        s = 1.0 / (decks * DEFAULT_SHARE_DIVISOR)
    score = s * BASE * LIMIT_FACTOR.get(limits.get(number), 1.0)
    w = int(WEIGHT_SCALE / score + 0.5)
    return max(1, min(w, 65535))


def main():
    out = sys.argv[1]
    bin_out = os.path.join(os.path.dirname(os.path.dirname(out)), 'assets', 'format_pack_roulettes.bin')
    lookup = banlist.card_lookup()
    missing = []
    lines = [
        '/* Generated by tools/format_packs.py. Do not edit. */',
        f'#define FORMAT_PACK_COUNT {len(banlist.BANLISTS)}',
        f'#define FORMAT_PACK_ID_FIRST {FORMAT_PACK_ID_FIRST}',
        f'#define VANILLA_PACK_INFO_COUNT {VANILLA_PACK_INFO_COUNT}',
        f'#define FORMAT_PACK_ROULETTE_SIZE {ROULETTE_SIZE}',
        '',
        'struct FormatPackEntry { u16 number; u16 weight; };',
        '',
    ]
    portrait_nums = []
    for name in PORTRAIT_NAMES:
        nums = lookup(name)
        if nums is None:
            print(f'format_packs: no EDS card for portrait "{name}"', file=sys.stderr)
            portrait_nums.append(0)
        else:
            portrait_nums.append(min(nums))

    lines.append('static const u16 sFormatPackPortraitNumber[FORMAT_PACK_COUNT] = {')
    lines.append('    ' + ', '.join(str(n) for n in portrait_nums) + ',')
    lines.append('};')
    lines.append('')
    lines.append('static const u16 sFormatPackDuelist[FORMAT_PACK_COUNT] = {')
    lines.append('    ' + ', '.join(str(d) for d in FORMAT_DUELISTS) + ',')
    lines.append('};')
    lines.append('')

    pool_lines = []
    roulette_ptrs = []
    roulette_blob = bytearray()
    for i, (fmt_name, stem, pools) in enumerate(banlist.BANLISTS):
        limits, _ = banlist.read_limits(f'banlists/{stem}_ban.json', lookup, missing)
        pool = set()
        for pool_stem in pools:
            pool |= banlist.read_pool(f'card_pools/{pool_stem}.txt', lookup, missing)
        total, extra, decks = usage_maps(stem, lookup, missing)
        entries = []
        for number in sorted(pool):
            if number == 0:
                continue
            w = card_weight(number, total, extra, decks, limits)
            if w is not None:
                entries.append((number, w))
        lines.append(f'/* {fmt_name} ({len(entries)} cards) */')
        lines.append(f'static const struct FormatPackEntry sFormatPackPool{i}[] = {{')
        for j in range(0, len(entries), 6):
            chunk = entries[j:j + 6]
            lines.append('    ' + ', '.join(f'{{ {n}, {w} }}' for n, w in chunk) + ',')
        lines.append('};')
        roulette = build_roulette(entries, stem)
        for n in roulette:
            roulette_blob += struct.pack('<H', n)
        pool_lines.append(f'    {{ sFormatPackPool{i}, {len(entries)} }},')
        roulette_ptrs.append(f'    &gFormatPackRouletteBlob[{i} * FORMAT_PACK_ROULETTE_SIZE],')

    os.makedirs(os.path.dirname(bin_out), exist_ok=True)
    try:
        if open(bin_out, 'rb').read() != roulette_blob:
            open(bin_out, 'wb').write(roulette_blob)
    except FileNotFoundError:
        open(bin_out, 'wb').write(roulette_blob)

    lines.append(
        'extern const u16 gFormatPackRouletteBlob[FORMAT_PACK_COUNT * FORMAT_PACK_ROULETTE_SIZE];'
    )
    lines.append('')
    lines.append('static const u16 *const sFormatPackRoulettes[FORMAT_PACK_COUNT] = {')
    lines.extend(roulette_ptrs)
    lines.append('};')
    lines.append('')

    lines.append('static const struct FormatPackPool {')
    lines.append('    const struct FormatPackEntry *entries;')
    lines.append('    u16 count;')
    lines.append('} sFormatPackPools[FORMAT_PACK_COUNT] = {')
    lines.extend(pool_lines)
    lines.append('};')
    lines.append('')

    names = [b[0] for b in banlist.BANLISTS]
    lines.append('static const char *const sFormatPackNames[FORMAT_PACK_COUNT] = {')
    for n in names:
        lines.append(f'    "{n}",')
    lines.append('};')
    lines.append('')

    banlist.write_if_changed(out, '\n'.join(lines))
    print(f'format_packs: {len(set(missing))} usage/pool names skipped (no EDS card)', file=sys.stderr)


if __name__ == '__main__':
    main()
