#!/usr/bin/env python3
"""The pre-duel screen's text and picture table (src/mod_preduel.c), from duelists/preduel_text.txt.

  python3 tools/preduel_text.py build/assets/preduel_text.bin build/assets/preduel_table.inc

preduel_text.bin: by duelist ID 0-24, 5 lines of PREDUEL_LINE bytes (ASCII, NUL-padded): the opponent's section of
  duelists/preduel_text.txt, or zeros. Hex Maniac Advance edits it as data.preduel.text (tools/hma_toml.py).
preduel_table.inc: by duelist ID, { picture, qr, scene } pointers for data/mod_preduel_data.s: the opponent's own
  pre-duel picture data (gModPreDuel<Name>, tools/preduel_image.py) when duelists/<name>.png is in the Makefile's
  PREDUEL_NAMES, else 0; its QR code from that data when it has duelists/<name>.svg, else Yugi-Kaiba's; and its
  entry in gModPreDuelScenes (PREDUEL_SCENE_ENTRY bytes each, PREDUEL_SCENE_COUNT of them, set at the end): its
  duelist's scene from the original pre-duel dialogue, which tools/preduel_scenes.py fills in the linked ROM and the
  game shows when the picture is 0. An opponent without a text section gets { 0, 0, 0 } and no pre-duel screen.
A section's name is the opponent's name (src/mod_opponents.c sOpponents) in lower case with - for spaces.
"""
import os
import re
import sys

TEXT = 'duelists/preduel_text.txt'
LINES, PREDUEL_LINE = 5, 48         # 47 characters and a NUL; 38 fit inside the box's border (x 24-216)
VISIBLE = 38
PREDUEL_SCENE_ENTRY = 256 * 2 + 240 * 96 + 256 * 2 + 0x2000    # tools/preduel_scenes.py
DEFAULT_QR = 'yugi-kaiba'


def slug(name):
    return name.lower().replace(' ', '-')


def label(s):
    return 'gModPreDuel' + ''.join(part.capitalize() for part in s.split('-'))


def opponents():
    """{slug: duelist ID} of the opponents with a name in sOpponents."""
    src = open('src/mod_opponents.c', encoding='utf-8').read()
    names = dict(re.findall(r'static const char (sName\w+)\[\] = "([^"]*)";', src))
    ids = {n: int(v) for n, v in re.findall(r'(DUELIST_\w+) = (\d+)',
                                            open('include/constants/game.h', encoding='utf-8').read())}
    out = {}
    for duelist, sym in re.findall(r'\[(DUELIST_\w+)\] = (?:FORMAT\(\d+, \w+, |DECK(?:_ALWAYS)?\()(sName\w+)', src):
        out[slug(names[sym])] = ids[duelist]
    return out


def sections():
    out, cur = {}, None
    for n, line in enumerate(open(TEXT, encoding='utf-8').read().split('\n'), 1):
        line = line.rstrip('\r').rstrip()
        if line.startswith('#'):
            continue
        m = re.fullmatch(r'\[([\w-]+)\]', line.strip())
        if m:
            cur = out.setdefault(m.group(1), [])
            continue
        if cur is None or (not line and not cur):
            continue
        if len(line) > VISIBLE:
            sys.exit(f'{TEXT}:{n}: {len(line)} characters, at most {VISIBLE} fit on the screen')
        cur.append(line)
    for name, lines in out.items():
        while lines and not lines[-1]:
            lines.pop()
        if len(lines) > LINES:
            sys.exit(f'{TEXT}: [{name}] has {len(lines)} lines, at most {LINES}')
    return out


def main():
    text_out, table_out = sys.argv[1:3]
    opp = opponents()
    text = sections()
    unknown = sorted(set(text) - set(opp))
    if unknown:
        sys.exit(f'{TEXT}: no opponent named {", ".join(unknown)} (src/mod_opponents.c)')
    pictures = set(re.search(r'^PREDUEL_NAMES\s*:=\s*(.*)$', open('Makefile', encoding='utf-8').read(),
                             re.M).group(1).split())
    data = bytearray(25 * LINES * PREDUEL_LINE)
    rows = ['@ Generated by tools/preduel_text.py from duelists/preduel_text.txt. Do not edit.',
            '@ { picture, qr, scene } by duelist ID (src/mod_preduel.c)']
    scenes = 0
    by_id = {d: s for s, d in opp.items()}
    for duelist in range(25):
        name = by_id.get(duelist)
        if name in text:
            for k, line in enumerate(text[name]):
                at = (duelist * LINES + k) * PREDUEL_LINE
                data[at:at + len(line)] = line.encode('ascii')
            picture = label(name) if name in pictures else '0'
            qr = label(name) if name in pictures and os.path.exists(f'duelists/{name}.svg') else label(DEFAULT_QR)
            # every opponent gets its duelist's scene copy; the game uses it when the picture is 0 (so a picture can
            # be switched off in Hex Maniac Advance by setting data.preduel.table's picture to null)
            scene = f'gModPreDuelScenes + {scenes} * {PREDUEL_SCENE_ENTRY}'
            scenes += 1
        else:
            picture = qr = scene = '0'
        rows.append(f'\t.4byte {picture}, {qr}, {scene}\t@ {duelist} {name or ""}')
    rows.append(f'\t.set PREDUEL_SCENE_COUNT, {scenes}')
    rows.append(f'\t.set PREDUEL_SCENE_ENTRY, {PREDUEL_SCENE_ENTRY}')
    os.makedirs(os.path.dirname(text_out), exist_ok=True)
    for path, content in ((text_out, bytes(data)), (table_out, ('\n'.join(rows) + '\n').encode())):
        if not os.path.exists(path) or open(path, 'rb').read() != content:
            open(path, 'wb').write(content)


if __name__ == '__main__':
    main()
