#!/usr/bin/env python3
"""Emit tools/testing_scenarios/format_decks.lua from usage/<format>.json.

For each Campaign format, picks the deck archetype with the highest deck count in that
usage file, then expands its ``total`` main-deck stats to a 40-card list (modal copies per
card). Lua applies this to both duelists before scenario hand/field RAM setup.

  python3 tools/gen_format_decks_lua.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
USAGE = ROOT / 'usage'
OUT = ROOT / 'tools' / 'testing_scenarios' / 'format_decks.lua'

# Keep in sync with tools/banlist.py BANLISTS[*][1]
FORMAT_STEMS = [
    'yugi-kaiba', 'critter', 'treasure', 'imperial', 'android', 'joey-pegasus',
    'fiber', 'yata', 'scientist', 'vampire', 'chaos', 'warrior', 'goat', 'cyber', 'reaper',
]

TARGET_MAIN = 40
TARGET_EXTRA = 15


def copies_per_deck(entry: dict) -> int:
    copies = entry.get('copies') or {}
    if not copies:
        return 1
    return max(int(k) for k in copies)


def expand_list(entries: list[dict], target: int) -> list[str]:
    if not entries:
        return []
    out: list[str] = []
    for entry in entries:
        name = entry.get('name') or ''
        if not name:
            continue
        n = copies_per_deck(entry)
        for _ in range(n):
            out.append(name)
            if len(out) >= target:
                return out
    i = 0
    while len(out) < target:
        out.append(entries[i % len(entries)]['name'])
        i += 1
    return out[:target]


def top_deck_type(data: dict) -> tuple[str, dict] | None:
    types = data.get('deck_types') or {}
    if not types:
        return None
    best_name, best = max(types.items(), key=lambda kv: kv[1].get('count', 0))
    return best_name, best


def build_format(stem: str) -> dict | None:
    path = USAGE / f'{stem}.json'
    if not path.is_file():
        return None
    data = json.loads(path.read_text(encoding='utf-8'))
    picked = top_deck_type(data)
    if not picked:
        return None
    deck_name, deck = picked
    main_src = deck.get('total') or deck.get('main') or []
    extra_src = deck.get('extra') or []
    return {
        'deckType': deck_name,
        'decksProcessed': data.get('decks_processed', 0),
        'main': expand_list(main_src, TARGET_MAIN),
        'extra': expand_list(extra_src, TARGET_EXTRA) if extra_src else [],
    }


def lua_quote(s: str) -> str:
    return json.dumps(s)


def emit_lua(formats: dict[str, dict]) -> str:
    lines = [
        '-- AUTO-GENERATED by tools/gen_format_decks_lua.py — do not edit.',
        '-- Most-played deck archetype per format (usage/*.json deck_types by count).',
        'return {',
    ]
    for stem in sorted(formats):
        spec = formats[stem]
        lines.append(f'    [{lua_quote(stem)}] = {{')
        lines.append(f'        deckType = {lua_quote(spec["deckType"])},')
        lines.append(f'        decksProcessed = {spec["decksProcessed"]},')
        lines.append('        main = {')
        for name in spec['main']:
            lines.append(f'            {lua_quote(name)},')
        lines.append('        },')
        if spec['extra']:
            lines.append('        extra = {')
            for name in spec['extra']:
                lines.append(f'            {lua_quote(name)},')
            lines.append('        },')
        lines.append('    },')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main() -> int:
    formats: dict[str, dict] = {}
    for stem in FORMAT_STEMS:
        spec = build_format(stem)
        if spec:
            formats[stem] = spec
            print(f'{stem}: {spec["deckType"]} ({len(spec["main"])} main)')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    # normalize key for emit
    emit_specs = formats
    OUT.write_text(emit_lua(emit_specs), encoding='utf-8')
    print(f'Wrote {OUT}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
