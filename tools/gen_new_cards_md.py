#!/usr/bin/env python3
"""Regenerate repo-root demo_cards.txt and NEW_CARDS.md from the last demo build's added cards.

  python3 tools/gen_new_cards_md.py

demo_cards.txt: every card the demo build adds, in alphabetical order, one per line ("name", or "name | in-game
name" when the game shows a shorter one): the cards of the repo-root new_cards.txt (above ------) and the leftover
effect cards (config/leftover_cards.txt, at their own card numbers), not make demo's blank slots. It is read from
build/new_cards.tsv (tools/newcards.py), so run it after `make demo` or `make release-demo`.
NEW_CARDS.md: the gallery of those cards, in the same order, from the screenshots in cards/ (tools/card_screenshots.lua).
"""

import os
import sys
from pathlib import Path
from urllib.parse import quote

TSV = "build/new_cards.tsv"
CARD_LIST = "demo_cards.txt"


def demo_build(root: Path) -> bool:
    """Whether build/new_cards.tsv is a demo build's (make demo or make release-demo), from newcards' stamp."""
    return any((root / "build/assets" / s).exists() for s in (".newcards-demo", ".newcards-demo-padded"))


def build_cards(root: Path) -> list[tuple[str, str]]:
    """[(name, in-game name)] of the added cards in build/new_cards.tsv (not the blank slots), alphabetical."""
    rows = (root / TSV).read_text(encoding="utf-8").splitlines()[1:]
    cards = []
    for row in rows:
        p = row.split("\t")
        if len(p) >= 5 and p[3]:
            cards.append((p[3], p[4] or p[3]))
    return sorted(cards, key=lambda c: (c[0].casefold(), c[0]))


def write_card_list(root: Path, cards: list[tuple[str, str]]) -> None:
    head = ("# Every card the demo build adds (the repo-root new_cards.txt and config/leftover_cards.txt), in alphabetical\n"
            "# order: \"name\", or \"name | in-game name\". Generated by tools/gen_new_cards_md.py from build/new_cards.tsv;\n"
            "# do not edit (edit new_cards.txt or config/leftover_cards.txt).\n")
    lines = [name if game == name else f"{name} | {game}" for name, game in cards]
    (root / CARD_LIST).write_text(head + "\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def load_card_list(path: Path) -> list[str]:
    names: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        names.append(line.split("|", 1)[0].strip())
    return names


def file_name(name: str) -> str:
    r"""The screenshot's file name, as tools/card_screenshots.lua's fileName writes it (<>:"/\|?* become _)."""
    return "".join("_" if ch in r'<>:"/\|?*' else ch for ch in name)


def img_cell(name: str) -> str:
    enc = quote(file_name(name), safe="")
    return (
        f'<td align="center">'
        f'<img src="cards/{enc}.png" alt="{name}" width="240"></td>'
    )


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    if not (root / TSV).exists() or not demo_build(root):
        sys.exit(f"gen_new_cards_md: {TSV} is not a demo build's; run make demo first")
    write_card_list(root, build_cards(root))
    cards = load_card_list(root / CARD_LIST)
    missing = [n for n in cards if not (root / "cards" / f"{file_name(n)}.png").exists()]
    rows: list[str] = []
    for i in range(0, len(cards), 4):
        chunk = cards[i : i + 4]
        cells = "".join(img_cell(n) for n in chunk)
        while len(chunk) < 4:
            cells += '<td></td>'
            chunk.append("")
        rows.append(f"<tr>\n{cells}\n</tr>")

    body = "\n".join(rows)
    n = len(cards)
    md = f"""# New cards

The {n} cards the demo build adds, in alphabetical order ([`demo_cards.txt`](demo_cards.txt): the repo-root `new_cards.txt` above `------`, and the cards of the engine's leftover effects in `config/leftover_cards.txt`), as the game shows them in Deck Edit's Card View. The screenshots are taken by [`tools/card_screenshots.lua`](tools/card_screenshots.lua) in mGBA.

<table>
{body}
</table>
"""
    (root / "NEW_CARDS.md").write_text(md, encoding="utf-8", newline="\n")
    print(f"NEW_CARDS.md: {n} cards ({CARD_LIST}); {len(missing)} without a screenshot in cards/")
    for name in missing:
        print(f"  {name}")


if __name__ == "__main__":
    main()
