#!/usr/bin/env python3
"""Password-machine card prices (DP) from deck usage statistics, for src/mod_dp.c.

  python3 tools/cardprices.py build/include/card_prices.h       # the Makefile runs it

Input: USAGE, a usage file ("decks_processed" decks; "total" = main + side and "extra" lists of
{ "name", "count", "copies": {"1": decks, "2": decks, "3": decks} }), and BANLIST, the list the usage comes from.
A card's price:
  main + side   the share of decks that run it ("total": the sum of its "copies" over decks_processed) * 1000
  extra         the same share of its "extra" entry * 1000 / 10 (the extra deck is worth less)
the two added, times 3 if the card is limited and 1.5 if semi-limited on BANLIST, rounded. A card of POOL that no
deck uses costs UNUSED_PRICE; cards outside the pool keep mod_dp.c's DEFAULT_CARD_COST. Names are matched as tools/banlist.py matches them (its aliases included).
"""
import json
import sys

sys.path.insert(0, 'tools')
import banlist  # noqa: E402

USAGE = 'usage/yugi-kaiba.json'
BANLIST = 'banlists/yugi-kaiba_ban.json'
POOL = 'card_pools/yugi-kaiba.txt'
UNUSED_PRICE = 5
BASE = 1000
EXTRA_DIVISOR = 10
LIMIT_FACTOR = {1: 3.0, 2: 1.5}         # limited, semi-limited


def share(entry, decks):
    return sum(entry['copies'].values()) / decks


def main():
    out = sys.argv[1]
    lookup = banlist.card_lookup()
    usage = json.load(open(USAGE, encoding='utf-8'))
    decks = usage['decks_processed']
    missing = []
    limits, _ = banlist.read_limits(BANLIST, lookup, missing)
    prices = {}         # card number -> DP (before the limit factor)
    for key, factor in (('total', 1.0), ('extra', 1.0 / EXTRA_DIVISOR)):
        for entry in usage.get(key, []):
            numbers = lookup(entry['name'])
            if numbers is None:
                missing.append(entry['name'])
                continue
            for number in numbers:
                prices[number] = prices.get(number, 0.0) + share(entry, decks) * BASE * factor
    rows = []
    for number in sorted(prices):
        price = prices[number] * LIMIT_FACTOR.get(limits.get(number), 1.0)
        rows.append((number, max(1, int(price + 0.5))))
    for number in banlist.read_pool(POOL, lookup, []) - set(prices):
        rows.append((number, UNUSED_PRICE))
    rows.sort()
    for name in sorted(set(missing)):
        print(f'cardprices: no EDS card named "{name}" (skipped)', file=sys.stderr)

    lines = [f'/* Generated by tools/cardprices.py from {USAGE} and {BANLIST}. Do not edit. */',
             '/* DP to buy a card with a password: { card number, price }, sorted by card number. */',
             'static const struct CardCost sCardCosts[] = {']
    lines += [f'    {{ {n}, {c} }},' for n, c in rows]
    lines += ['};', '']
    banlist.write_if_changed(out, '\n'.join(lines))


if __name__ == '__main__':
    main()
