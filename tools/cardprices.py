#!/usr/bin/env python3
"""Password-machine card prices (DP) from deck usage statistics, for src/mod_dp.c.

  python3 tools/cardprices.py build/include/card_prices.h       # the Makefile runs it
  python3 tools/cardprices.py --md CARD_PRICES.md               # the same prices as a Markdown table per format

One price table per format, in the order of tools/banlist.py's BANLISTS (the banlist indices), from
usage/<stem>.json ("decks_processed" decks; "total" = main + side and "extra" lists of
{ "name", "count", "copies": {"1": decks, "2": decks, "3": decks} }) and the format's banlist:
  main + side   the share of decks that run the card ("total": the sum of its "copies" over decks_processed) * 1000
  extra         the same share of its "extra" entry * 1000 / 10 (the extra deck is worth less)
the two added, times 3 if the card is limited and 1.5 if semi-limited in that format, rounded (at least MIN_PRICE).
A table lists only the cards the format's decks use. At run time GetCardCost (src/mod_dp.c) takes the price from
the newest unlocked format whose decks use the card; a card none of them uses costs MIN_PRICE (POOL_CARD_COST) if it
is in an unlocked format's card pool, else DEFAULT_CARD_COST.
Names are matched as tools/banlist.py matches them (its aliases included).
"""
import json
import sys

sys.path.insert(0, 'tools')
import banlist  # noqa: E402

BASE = 1000
EXTRA_DIVISOR = 10
LIMIT_FACTOR = {1: 3.0, 2: 1.5}         # limited, semi-limited
DEFAULT_CARD_COST = 3000                # src/mod_dp.c's, for --md
MIN_PRICE = 20                          # the cheapest a card costs; src/mod_dp.c's POOL_CARD_COST is the same


def share(entry, decks):
    return sum(entry['copies'].values()) / decks


def format_prices(stem, lookup, missing):
    """{card number: price} of the cards format `stem`'s decks use."""
    usage = json.load(open(f'usage/{stem}.json', encoding='utf-8'))
    decks = usage['decks_processed']
    limits, _ = banlist.read_limits(f'banlists/{stem}_ban.json', lookup, [])
    prices = {}
    for key, factor in (('total', 1.0), ('extra', 1.0 / EXTRA_DIVISOR)):
        for entry in usage.get(key, []):
            numbers = lookup(entry['name'])
            if numbers is None:
                missing.append(entry['name'])
                continue
            for number in numbers:
                prices[number] = prices.get(number, 0.0) + share(entry, decks) * BASE * factor
    return {n: max(MIN_PRICE, int(p * LIMIT_FACTOR.get(limits.get(n), 1.0) + 0.5)) for n, p in prices.items()}


def main():
    out = sys.argv[1]
    lookup = banlist.card_lookup()
    missing = []
    lines = ['/* Generated by tools/cardprices.py from usage/*.json and banlists/*_ban.json. Do not edit. */',
             '/* DP to buy a card with a password, per format (banlist index): { card number, price }, sorted. */', '']
    rows = []
    for i, (name, stem, _pools) in enumerate(banlist.BANLISTS):
        prices = format_prices(stem, lookup, missing)
        lines.append(f'/* {name} */')
        lines.append(f'static const struct CardCost sCardCosts{i}[] = {{')
        lines += [f'    {{ {n}, {c} }},' for n, c in sorted(prices.items())]
        lines += ['};', '']
        rows.append(f'    {{ sCardCosts{i}, {len(prices)} }},')
    lines.append('static const struct CardCostTable sFormatCardCosts[] = {')
    lines += rows
    lines += ['};', '']
    # Later formats' decks use many cards EDS does not have; only their number is reported.
    print(f'cardprices: {len(set(missing))} card names in the usage statistics have no EDS card (skipped)',
          file=sys.stderr)
    banlist.write_if_changed(out, '\n'.join(lines))


def card_names():
    """{card number: name} of the built cards (the base number of an alternate art)."""
    names = open(banlist.NAMES, 'rb').read()
    i2n = open(banlist.ID_TO_NUMBER, 'rb').read()
    out = {}
    for cid in range(1, len(i2n) // 2):
        number = int.from_bytes(i2n[cid * 2:cid * 2 + 2], 'little')
        name = names[cid * banlist.NAME_SIZE:(cid + 1) * banlist.NAME_SIZE].split(b'\0')[0].decode('latin-1')
        if number != 0xFFFF and name and number < banlist.ALT_ART:
            out.setdefault(number, name)
    return out


def markdown(out):
    """CARD_PRICES.md: each format's own prices, the cards its decks use (no carried-over or card pool prices)."""
    lookup = banlist.card_lookup()
    names = card_names()
    lines = ['# Card Prices', '',
             'The DP the card password machine charges, per format, from the format\'s deck usage statistics '
             '(`usage/`). Generated by `python3 tools/cardprices.py --md CARD_PRICES.md`; do not edit.', '',
             '- **Price.** The share of the format\'s decks that run the card (main + side) times 1000, plus its '
             'Extra Deck share times 100; times 3 if the card is Limited in that format, times 1.5 if Semi-Limited; '
             f'at least {MIN_PRICE} DP.',
             '- **Which format.** The game uses the newest format you have unlocked whose decks use the card.',
             '- **Not listed.** Cards a format\'s decks don\'t use: those keep their price from an earlier format, '
             f'cost {MIN_PRICE} DP if they are in an unlocked format\'s card pool, and {DEFAULT_CARD_COST} DP otherwise.', '']
    lines.append('| Format | Cards priced |')
    lines.append('|---|---|')
    tables = []
    for name, stem, _pools in banlist.BANLISTS:
        prices = format_prices(stem, lookup, [])
        limits, _ = banlist.read_limits(f'banlists/{stem}_ban.json', lookup, [])
        lines.append(f'| [{name}](#{stem}) | {len(prices)} |')
        tables += [f'## {name}', '', '| Card | DP | Limit |', '|---|---:|---|']
        rows = []
        for n, c in sorted(prices.items(), key=lambda kv: (-kv[1], names.get(kv[0], ''))):
            limit = {1: 'Limited', 2: 'Semi-Limited'}.get(limits.get(n), '')
            row = f'| {names.get(n, n)} | {c} | {limit} |'
            if row not in rows:     # one card under two numbers (the two Polymerizations)
                rows.append(row)
        tables += rows
        tables.append('')
    lines.append('')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines + tables).rstrip('\n') + '\n')


if __name__ == '__main__':
    if sys.argv[1] == '--md':
        markdown(sys.argv[2])
    else:
        main()
