/* 1 if the player can buy card id (enough DP, and room in the trunk). */
int CanBuyCard(u16 id)
{
    return GetDP() >= GetCardCost(id) && gSaveData.trunk[id & CARD_ID_MASK].count < 0x3FF;
}

